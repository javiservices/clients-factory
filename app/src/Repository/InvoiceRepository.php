    public function findLastInvoiceOfYear(int $year): ?Invoice
    {
        return $this->createQueryBuilder('i')
            ->andWhere('i.invoiceNumber LIKE :year')
            ->setParameter('year', 'INV-' . $year . '-%')
            ->orderBy('i.invoiceNumber', 'DESC')
            ->setMaxResults(1)
            ->getQuery()
            ->getOneOrNullResult()
        ;
